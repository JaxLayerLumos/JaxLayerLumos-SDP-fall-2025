    # 2. Slice the list of thicknesses (Indices 5 through 9)
    thicknesses = row[5:10]

    # 3. Get the ref_R_in_db value (Index 11)
    ref_R = row[11]

    reversed_materials = list(reversed(materials))
    reversed_thicknesses = list(reversed(thicknesses))

